"""PyPI 发布器 — git-sync 子模块"""
import sys, os, shutil, subprocess, tempfile, json
from _paths import WORK_REPO

SETUP_PY_TEMPLATE = '''"""setup.py for {name} — auto-generated by git-sync"""
from setuptools import setup, find_packages
import os

with open(os.path.join(os.path.dirname(__file__), "rag_assistant", "__init__.py")) as f:
    for line in f:
        if line.startswith("__version__"):
            VERSION = line.split('"')[1]
            break
    else:
        VERSION = "{version}"

req_path = os.path.join(os.path.dirname(__file__), "requirements.txt")
with open(req_path, encoding="utf-8") as f:
    REQUIREMENTS = [l.strip() for l in f if l.strip() and not l.startswith("#")]
REQUIREMENTS = [r for r in REQUIREMENTS if not r.startswith("langchain")]

readme_path = os.path.join(os.path.dirname(__file__), "README.md")
if os.path.exists(readme_path):
    with open(readme_path, encoding="utf-8") as f:
        LONG_DESC = f.read()
else:
    LONG_DESC = "{name}: AI Agent"

# 追加当前版本的 CHANGELOG 到 long_description
changelog_path = os.path.join(os.path.dirname(__file__), "CHANGELOG.md")
if os.path.exists(changelog_path):
    with open(changelog_path, encoding="utf-8") as f:
        changelog_content = f.read()
    # 提取当前版本号对应的 changelog 区块
    import re
    version_escaped = re.escape(VERSION)
    m = re.search(r"##\s*\[" + version_escaped + r"\].*?(?=\n##\s*\[|\Z)", changelog_content, re.DOTALL)
    if m:
        version_changelog = m.group(0).strip()
        LONG_DESC += "\n\n---\n\n## 更新说明\n\n" + version_changelog

setup(
    name="{pypi_name}",
    version=VERSION,
    description="{name} — AI Agent",
    long_description=LONG_DESC,
    long_description_content_type="text/markdown",
    author="Ldxs (wUwproject)",
    author_email="wuwofc@yeah.net",
    url="https://github.com/Ldxs001/workbuddy-skills",
    packages=find_packages(),
    include_package_data=True,
    python_requires=">=3.10",
    install_requires=REQUIREMENTS,
    entry_points={{"console_scripts": ["{pypi_name}=main:main"]}},
    classifiers=[
        "Development Status :: 4 - Beta",
        "Intended Audience :: Developers",
        "License :: OSI Approved :: Apache Software License",
        "Programming Language :: Python :: 3",
        "Topic :: Scientific/Engineering :: Artificial Intelligence",
    ],
)
'''

MANIFEST_IN_TEMPLATE = """include requirements.txt
include README.md
include LICENSE
include CHANGELOG.md
include setup.py
include main.py
recursive-include scripts/ *.py
prune __pycache__
prune *.pyc
"""

def main():
    if len(sys.argv) < 4:
        print("用法: pypi_publish.py <source_dir> <name> <version>")
        sys.exit(1)
    src_dir, name, version = sys.argv[1], sys.argv[2], sys.argv[3]

    # 确定 PyPI 包名
    pypi_name = f"{name}-ldxs"

    # 创建隔离构建目录
    build_dir = os.path.join(tempfile.gettempdir(), f"pypi_build_{name}_{version}")
    if os.path.exists(build_dir):
        shutil.rmtree(build_dir)
    shutil.copytree(src_dir, build_dir, symlinks=False,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".git", "dist", "build", "*.egg-info"))

    # 写入 setup.py
    setup_content = SETUP_PY_TEMPLATE.format(name=name, version=version, pypi_name=pypi_name)
    with open(os.path.join(build_dir, "setup.py"), "w", encoding="utf-8") as f:
        f.write(setup_content)

    # 写入 MANIFEST.in
    with open(os.path.join(build_dir, "MANIFEST.in"), "w", encoding="utf-8") as f:
        f.write(MANIFEST_IN_TEMPLATE)

    # 读取 PyPI token（支持 HTTPS 和 SSH remote）
    remote_url = subprocess.run(
        ["git", "remote", "get-url", "origin"],
        cwd=str(WORK_REPO),
        capture_output=True, text=True
    ).stdout.strip()
    token = ""
    if "//" in remote_url and "@" in remote_url:
        # HTTPS: https://user:token@github.com/...
        token_part = remote_url.split("//")[1].split("@")[0]
        if ":" in token_part:
            token = token_part.split(":")[1]

    if not token:
        print("  ⚠️  无法获取 GitHub token，尝试 ~/.pypirc")
        # check env
        token = os.environ.get("PYPI_TOKEN", "")

    if not token:
        print("  ❌ 未找到 PyPI token")
        print("  设置方式: set PYPI_TOKEN=pypi-xxxxx")
        sys.exit(1)

    # build (only wheel, no sdist)
    print(f"  构建 {pypi_name} v{version}...")
    result = subprocess.run(
        [sys.executable, "-m", "build", "--wheel"],
        cwd=build_dir, capture_output=True, text=True
    )
    if result.returncode != 0:
        print(f"  ❌ 构建失败: {result.stderr[:300]}")
        sys.exit(1)

    # upload
    print(f"  上传到 PyPI...")
    result = subprocess.run(
        [sys.executable, "-m", "twine", "upload", "--disable-progress",
         f"dist/{pypi_name.replace('-', '_')}-{version}-py3-none-any.whl",
         "-u", "__token__", "-p", token],
        cwd=build_dir, capture_output=True, text=True
    )
    if result.returncode == 0:
        print(f"  ✅ PyPI: https://pypi.org/project/{pypi_name}/")
    else:
        print(f"  ❌ 上传失败: {result.stderr[:300]}")

    # cleanup
    shutil.rmtree(build_dir, ignore_errors=True)

if __name__ == "__main__":
    main()
