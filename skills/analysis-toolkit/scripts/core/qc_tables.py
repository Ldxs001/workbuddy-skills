# 允许值分级表（按数量级）
# 对应：检测浓度数量级 → 允许偏差(%)
# ============================================================
TOLERANCE_TABLE = {
    4: 1.0, 5: 2.5, 6: 6.0, 7: 10.0, 8: 20.0, 9: 30.0, 10: 50.0,
}


def get_tolerance(magnitude_order):
    """根据数量级获取允许偏差(%)。"""
    if magnitude_order in TOLERANCE_TABLE:
        return TOLERANCE_TABLE[magnitude_order]
    if magnitude_order < 4:
        return 1.0
    return min(magnitude_order * 5.0, 100.0)


def get_magnitude_order(value):
    """根据数值估算数量级指数。"""
    if value <= 0:
        return 6
    return int(np.floor(np.abs(np.log10(value))))


# ============================================================
# Z值质控判定标准（ISO 13528 / CNAS-GL002）
# ============================================================
def z_score_judgment(z):
    """Z值质控判定。"""
    if abs(z) <= 2:
        return "满意"
    elif abs(z) <= 3:
        return "可疑"
    return "不满意"


def calculate_z_score(x, assigned_value, std_dev):
    """Z值 = (结果 - 指定值) / 标准偏差"""
    if std_dev <= 0:
        raise ValueError("标准偏差必须大于0")
    return (x - assigned_value) / std_dev
